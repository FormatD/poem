// classifyTheme 返回题材名，判不出来返回空串。
func classifyTheme(title, text string) string {
	// 题名命中按规则顺序优先，先命中的题材更具体（边塞排在宴游之前）
	for _, r := range themeRules {
		for _, k := range r.title {
			if strings.Contains(title, k) {
				return r.name
			}
		}
	}
	type hit struct {
		name  string
		count int
	}
	var hits []hit
	for _, r := range themeRules {
		if len(r.text) == 0 {
			continue
		}
		n := 0
		for _, k := range r.text {
			if strings.Contains(text, k) {
				n++
			}
		}
		if n >= 2 {
			hits = append(hits, hit{r.name, n})
		}
	}
	if len(hits) == 0 {
		return ""
	}
	sort.Slice(hits, func(i, j int) bool {
		if hits[i].count != hits[j].count {
			return hits[i].count > hits[j].count
		}
		// 命中数打平时按规则表顺序，保持与题名判定一致的优先级
		for a, r := range themeRules {
			if r.name == hits[i].name {
				for b, s := range themeRules {
					if s.name == hits[j].name {
						return a < b
					}
				}
			}
		}
		return false
	})
	return hits[0].name
}

// classifySeason 只在全诗恰好出现一个季节字时给出季节，
// 这样「这句写的是哪个季节」的四个选项里只有一个能成立。
func classifySeason(text string) string {
	found := ""
	for _, s := range []string{"春", "夏", "秋", "冬"} {
		if strings.Contains(text, s) {
			if found != "" && found != s {
				return ""
			}
			found = s
		}
	}
	return found
}
